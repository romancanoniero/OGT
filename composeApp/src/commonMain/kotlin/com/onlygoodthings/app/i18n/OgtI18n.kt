/** Español latinoamericano por defecto. En LATAM se estaciona; no se “parquea”. */
enum class OgtLang(val code: String) {
    ES("es"),
    EN("en"),
    ;

    companion object {
        fun fromCode(code: String): OgtLang = if (code.equals("en", ignoreCase = true)) EN else ES
    }
}

