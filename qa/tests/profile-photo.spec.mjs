import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test.skip(process.env.OGT_FULL_E2E !== '1', 'Requires isolated QA services.');
test('existing comments and anecdotes use the current profile photo without changing other authors', async ({ page, context, request }, info) => {
  await context.route('**/*', r => ['localhost', '127.0.0.1'].includes(new URL(r.request().url()).hostname) ? r.continue() : r.abort());
  await page.goto('/#/registro');
  await page.getByLabel('Nombre y apellido').fill('Persona Foto QA');
  await page.getByLabel('Correo electrónico').fill(`qa-photo-${Date.now()}@example.test`);
  await page.getByLabel('Contraseña', {exact:true}).fill('OnlyGoodThings-QA-2468');
  await page.getByRole('button', {name:'Crear cuenta',exact:true}).click();
  await expect(page).toHaveURL(/#\/inicio/);
  const token = await page.evaluate(() => window.OgtAuth.getToken());
  const api = async (path,data={},bearer=token) => {
    const res=await request.post(`/api/v1/${path}`,{headers:{Authorization:`Bearer ${bearer}`},data});
    expect(res.ok()).toBe(true);const body=await res.json();expect(body.success).toBe(true);return body.data;
  };
  const me=await api('auth/me');
  const headerAvatar=page.locator(`.section-avatar img[data-user="${me.userId}"]`);
  await expect(headerAvatar).toHaveAttribute('src',/^avatars\/[^?]+\.(png|svg|jpg)$/);
  const emptyAvatar=await headerAvatar.getAttribute('src');
  const fixture=await readFile(new URL('../../backend/src/test/resources/images/transparent.webp',import.meta.url));
  const upload=()=>api('media/upload',{filename:'photo.webp',contentType:'image/webp',bytesBase64:fixture.toString('base64')});
  const first=await upload(),second=await upload();
  await api('users/profile/update',{displayName:'Persona Foto QA',photoUrl:first.url});
  const post=await api('social/publish',{body:'Un homenaje QA',topic:'Homenaje',honoreeName:'Persona QA',media:[{kind:'IMAGE',url:first.url}]});
  const comment=await api('social/comment',{postId:post.id,body:'Comentario anterior al cambio'});
  const story=await api('social/anecdote',{postId:post.id,body:'Anécdota anterior al cambio'});
  await api('social/comment',{postId:post.id,anecdoteId:story.id,body:'Respuesta de anécdota'});
  const signup=await request.post('http://127.0.0.1:19099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key',{data:{email:`qa-other-${Date.now()}@example.test`,password:'OnlyGoodThings-QA-2468',returnSecureToken:true}});
  expect(signup.ok()).toBe(true);const otherToken=(await signup.json()).idToken;
  const other=await api('auth/me',{},otherToken);
  await api('social/comment',{postId:post.id,body:'Otro autor sin foto'},otherToken);
  await api('social/comment',{postId:post.id,anecdoteId:story.id,body:'Otro autor en anécdota sin foto'},otherToken);
  await api('social/comment',{postId:post.id,parentCommentId:comment.id,body:'Respuesta anidada'});
  await page.goto('/#/p/'+post.id);
  await expect(page.locator('.reply').first()).toBeVisible();
  await api('users/profile/update',{displayName:'Persona Foto QA',photoUrl:second.url});
  await page.evaluate(({id,url})=>applyProfileLive({id,displayName:'Persona Foto QA',photoUrl:url}),{id:me.userId,url:second.url});
  const own=page.locator(`.reply img[data-user="${me.userId}"], .story-head img[data-user="${me.userId}"]`);
  await expect(own.nth(1)).toBeVisible();
  for(const img of await own.all())await expect(img).toHaveJSProperty('src',second.url);
  await expect(page.locator(`img[data-user="${other.userId}"]`).first()).toBeVisible();
  for(const img of await page.locator(`img[data-user="${other.userId}"]`).all())await expect(img).toHaveAttribute('src',emptyAvatar);
  await page.reload();
  await expect(page.locator('.reply').first()).toBeVisible();
  for(const img of await own.all())await expect(img).toHaveJSProperty('src',second.url);
  const rows=await api('social/comments',{postId:post.id});
  const row=rows.find(r=>r.id===comment.id);expect(row.authorPhotoUrl).toBe(second.url);expect(row.replies[0].authorPhotoUrl).toBe(second.url);
  const posts=await api('social/posts-by-author',{userId:me.userId});
  const fresh=posts.find(p=>p.id===post.id).anecdotes.find(a=>a.id===story.id);
  expect(fresh.authorPhotoUrl).toBe(second.url);expect(fresh.comments[0].authorPhotoUrl).toBe(second.url);
  const label='Encuadernación QA '+Date.now();
  const tags=await api('timebank/tag/create',{label});
  const tag=tags.find(t=>t.offered&&t.label.toLocaleLowerCase('es')===label.toLocaleLowerCase('es'));expect(tag).toBeTruthy();
  await api('timebank/skill',{tagSlug:tag.slug,offered:false,requested:true},otherToken);
  const board=await api('timebank/board',{},otherToken);
  expect(board.helpers.find(h=>h.userId===me.userId)?.photoUrl).toBe(second.url);
  await page.screenshot({path:info.outputPath('current-avatars.png'),fullPage:true});
});
